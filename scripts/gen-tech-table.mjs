// One-off generator: extracts the game's cost constants from OGLight's Datafinder table
// (OGLight, MIT, © 2019 Oz) into src/data/tech-table.ts. Run: node scripts/gen-tech-table.mjs <OGLight.user.js>
import { readFileSync, writeFileSync } from 'node:fs';
const src = readFileSync(process.argv[2], 'utf8');
const start = src.indexOf('class Datafinder');
const open = src.indexOf('let tech =', start);
const end = src.indexOf('return tech[parseInt(id)]', open);
const body = src.slice(src.indexOf('{', open), src.lastIndexOf('}', end) + 1);
const table = Function(`return (${body})`)();
const rows = [];
// Techs newer than OGLight's table. 45 Interstellar Anomaly Scanner (Orion, 13.1): 90/45/15 × 1.5^(L-1),
// checked in game: level 11 = 5189 / 2594 / 864.
const EXTRA = { 45: { metal: 90, crystal: 45, deut: 15, priceFactor: 1.5 } };
for (const [id, d] of Object.entries({ ...table, ...EXTRA })) {
  const row = [d.metal || 0, d.crystal || 0, d.deut || 0, d.priceFactor || 2, d.energy || 0, d.energyFactor || d.energyIncreaseFactor || 2, d.durationbase || 0, d.durationfactor || 2];
  rows.push(`  ${id}: [${row.join(', ')}],`);
}
const out = `/**
 * Game cost constants per technology id: [metal, crystal, deuterium, priceFactor, energy,
 * energyFactor, durationBase, durationFactor]. Generated by scripts/gen-tech-table.mjs from
 * OGLight's table (OGLight, MIT License, © 2019 Oz), plus the rows in its EXTRA list. Do not edit by hand.
 */
export type TechRow = readonly [number, number, number, number, number, number, number, number];

export const TECH_TABLE: Record<number, TechRow> = {
${rows.join('\n')}
};
`;
writeFileSync(new URL('../src/data/tech-table.ts', import.meta.url), out);
console.log(rows.length, 'rows');
